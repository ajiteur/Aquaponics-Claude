#!/usr/bin/env python3
"""Generate a repeatable first-slice reference audit from repo text files.

This helper scans the current working tree under aquaponics-project/ and reports
references for:
- crop_system_type
- saleable_harvest_mass_kg
- first-slice basil scenario paths
- reviewed-manual override flow

It intentionally excludes non-authoritative or noisy paths such as:
- .git/
- knowledge-vault/.obsidian/
- data/simulation/
- __pycache__/
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Iterable


PROJECT_ROOT = Path(__file__).resolve().parent.parent
TEXT_SUFFIXES = {".md", ".py", ".json", ".yaml", ".yml", ".txt"}
EXCLUDED_PARTS = {
    ".git",
    "__pycache__",
}
EXCLUDED_PREFIXES = (
    ("knowledge-vault", ".obsidian"),
    ("data", "simulation"),
)


@dataclass(frozen=True)
class AuditSection:
    title: str
    patterns: tuple[str, ...]


SECTIONS = (
    AuditSection(
        title="crop_system_type references",
        patterns=("crop_system_type",),
    ),
    AuditSection(
        title="saleable_harvest_mass_kg references",
        patterns=("saleable_harvest_mass_kg",),
    ),
    AuditSection(
        title="first-slice basil scenario path references",
        patterns=(
            "data/simulation/scenarios/starter_tilapia_basil_system.json",
            "data/simulation/scenarios/starter_tilapia_basil_system_day_1_day_2_day_3_day_4_day_5_day_6_day_7.json",
            "starter_tilapia_basil_system_day_1_day_2_day_3_day_4_day_5_day_6_day_7.json",
        ),
    ),
    AuditSection(
        title="reviewed-manual override flow references",
        patterns=(
            "example_first_slice_reviewed_manual_overrides.json",
            "--overrides",
            "reviewed-manual override",
            "reviewed manual override",
            "reviewed_manual_input",
        ),
    ),
)


def should_scan(path: Path) -> bool:
    if path.suffix.lower() not in TEXT_SUFFIXES:
        return False

    parts = path.relative_to(PROJECT_ROOT).parts
    if any(part in EXCLUDED_PARTS for part in parts):
        return False

    for prefix in EXCLUDED_PREFIXES:
        if parts[: len(prefix)] == prefix:
            return False

    return True


def iter_text_files() -> Iterable[Path]:
    for path in sorted(PROJECT_ROOT.rglob("*")):
        if path.is_file() and should_scan(path):
            yield path


def collect_matches(patterns: tuple[str, ...]) -> list[tuple[str, int, str]]:
    matches: list[tuple[str, int, str]] = []
    lowered = tuple(pattern.lower() for pattern in patterns)

    for path in iter_text_files():
        rel_path = path.relative_to(PROJECT_ROOT).as_posix()
        try:
            lines = path.read_text(encoding="utf-8").splitlines()
        except UnicodeDecodeError:
            continue

        for lineno, line in enumerate(lines, start=1):
            line_lower = line.lower()
            if any(pattern in line_lower for pattern in lowered):
                matches.append((rel_path, lineno, line.strip()))

    return matches


def render_section(section: AuditSection) -> str:
    matches = collect_matches(section.patterns)
    files = sorted({path for path, _, _ in matches})

    lines = [
        f"## {section.title}",
        "",
        f"- hits: `{len(matches)}`",
        f"- files: `{len(files)}`",
        "",
    ]

    if not matches:
        lines.append("- no matches found")
        lines.append("")
        return "\n".join(lines)

    current_path: str | None = None
    for path, lineno, text in matches:
        if path != current_path:
            lines.append(f"- `{path}`")
            current_path = path
        lines.append(f"  - line {lineno}: `{text}`")

    lines.append("")
    return "\n".join(lines)


def main() -> int:
    scanned_count = sum(1 for _ in iter_text_files())

    lines = [
        "# First Slice Repo Audit",
        "",
        "Generated by `scripts/generate_first_slice_repo_audit.py`.",
        "",
        "## Scan Scope",
        "",
        f"- project root: `{PROJECT_ROOT.as_posix()}`",
        f"- scanned text files: `{scanned_count}`",
        "- excluded paths:",
        "  - `.git/**`",
        "  - `knowledge-vault/.obsidian/**`",
        "  - `data/simulation/**`",
        "  - `__pycache__/**`",
        "",
    ]

    for section in SECTIONS:
        lines.append(render_section(section).rstrip())

    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
